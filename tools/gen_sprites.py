def rows_bytes(rows):
    w=len(rows[0]); bw=(w+7)//8; out=[]
    for r in rows:
        assert len(r)==w, r
        for b in range(bw):
            v=0
            for bit in range(8):
                i=b*8+bit
                if i<w and r[i]=='X': v|=0x80>>bit
            out.append(v)
    return w,len(rows),out

def emit():
    print("// ---- AUTO-GENERATED by tools/gen_sprites.py (edit the ASCII art there) ----")
    for name,rows in ART.items():
        w,h,b=rows_bytes(rows)
        for r in rows: print("//   "+r)
        print("const uint8_t spr_%s[] PROGMEM = {%d,%d, %s};"%(name,w,h,
              ",".join("0x%02X"%x for x in b)))

def png(path):
    from PIL import Image
    S=8; names=list(ART); MAXW=60
    placed=[]; x=1; y=1; rowh=0
    for n in names:
        w=len(ART[n][0]); h=len(ART[n])
        if x+w+1>MAXW: x=1; y+=rowh+2; rowh=0
        placed.append((n,x,y)); x+=w+2; rowh=max(rowh,h)
    H=y+rowh+2
    im=Image.new("L",(MAXW*S,H*S),200)
    for n,x0,y0 in placed:
        for j,r in enumerate(ART[n]):
            for i,c in enumerate(r):
                if c=='X':
                    for a in range(S):
                        for b in range(S): im.putpixel(((x0+i)*S+a,(y0+j)*S+b),0)
    im.save(path)

