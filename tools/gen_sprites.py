def rows_bytes(rows):
    w=len(rows[0]); bw=(w+7)//8; out=[]
    for r in rows:
        assert len(r)==w, r
        for b in range(bw):
            v=0
            for bit in range(8):
                i=b*8+bit
                if i<w and r[i]=='X': v|=0x80>>bit
            out.append(v)
    return w,len(rows),out

def emit():
    print("// ---- AUTO-GENERATED by tools/gen_sprites.py (edit the ASCII art there) ----")
    for name,rows in ART.items():
        w,h,b=rows_bytes(rows)
        for r in rows: print("//   "+r)
        print("const uint8_t spr_%s[] PROGMEM = {%d,%d, %s};"%(name,w,h,
              ",".join("0x%02X"%x for x in b)))

def png(path):
    from PIL import Image
    S=10; cell=[]; x=2
    names=list(ART)
    W=sum(len(ART[n][0])+2 for n in names)+2; H=14
    im=Image.new("L",(W*S,H*S),200)
    x=2
    for n in names:
        for j,r in enumerate(ART[n]):
            for i,c in enumerate(r):
                if c=='X':
                    for a in range(S):
                        for b in range(S): im.putpixel(((x+i)*S+a,(2+j)*S+b),0)
        x+=len(ART[n][0])+2
    im.save(path)

